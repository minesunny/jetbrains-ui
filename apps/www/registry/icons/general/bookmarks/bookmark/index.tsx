import { cn } from '@/lib/utils';

export type BookmarkProps = Omit<ComponentProps<'svg'>, 'size'> & {
  size?: 12 | 14 | 16 | 20 | 24;
  mode?: 'light' | 'dark';
};

const BookmarkLight: FC<
  Omit<ComponentProps<'svg'>, 'size'> & { size: number }
> = ({
  size,
  className,
  role,
  'aria-label': ariaLabel,
  'aria-hidden': ariaHidden,
}) => (
  <svg
    width={size}
    height={size}
    viewBox="0 0 16 16"
    fill="none"
    xmlns="http://www.w3.org/2000/svg"
    className={className}
    role={role}
    aria-label={ariaLabel}
    aria-hidden={ariaHidden}
  >
    <path
      d="M3 3.5a2 2 0 0 1 2-2h5.999a2 2 0 0 1 2 2v11.418a.5.5 0 0 1-.813.39L8 11.953 3.813 15.31a.5.5 0 0 1-.813-.39z"
      fill="#FFAF0F"
    />
  </svg>
);

const BookmarkDark: FC<
  Omit<ComponentProps<'svg'>, 'size'> & { size: number }
> = ({
  size,
  className,
  role,
  'aria-label': ariaLabel,
  'aria-hidden': ariaHidden,
}) => (
  <svg
    width={size}
    height={size}
    viewBox="0 0 16 16"
    fill="none"
    xmlns="http://www.w3.org/2000/svg"
    className={className}
    role={role}
    aria-label={ariaLabel}
    aria-hidden={ariaHidden}
  >
    <path
      d="M3 3.5a2 2 0 0 1 2-2h5.999a2 2 0 0 1 2 2v11.418a.5.5 0 0 1-.813.39L8 11.953 3.813 15.31a.5.5 0 0 1-.813-.39z"
      fill="#F2C55C"
    />
  </svg>
);

export const Bookmark: FC<BookmarkProps> = ({
  size = 16,
  mode = 'light',
  className,
  'aria-label': ariaLabel,
  ...props
}) => {
  const SvgComponent = mode === 'light' ? BookmarkLight : BookmarkDark;

  return (
    <SvgComponent
      size={size}
      className={cn('inline-block shrink-0', className)}
      role={ariaLabel ? 'img' : 'presentation'}
      aria-label={ariaLabel}
      aria-hidden={!ariaLabel}
      {...props}
    />
  );
};

export default Bookmark;
