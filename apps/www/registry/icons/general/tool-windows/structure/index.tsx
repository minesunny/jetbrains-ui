import type { ComponentProps, FC } from 'react';
import { cn } from '@/lib/utils';

export type StructureProps = Omit<ComponentProps<'svg'>, 'size'> & {
  size?: 12 | 14 | 16 | 20 | 24;
  mode?: 'light' | 'dark';
};

const StructureLight: FC<
  Omit<ComponentProps<'svg'>, 'size'> & { size: number }
> = ({
  size,
  className,
  role,
  'aria-label': ariaLabel,
  'aria-hidden': ariaHidden,
}) => (
  <svg
    width={size}
    height={size}
    viewBox="0 0 16 16"
    fill="none"
    xmlns="http://www.w3.org/2000/svg"
    className={className}
    role={role}
    aria-label={ariaLabel}
    aria-hidden={ariaHidden}
  >
    <rect x={8.5} y={8.5} width={5} height={5} rx={0.5} stroke="#6C707E" />
    <rect x={1.5} y={8.5} width={5} height={5} rx={0.5} stroke="#6C707E" />
    <rect x={1.5} y={1.5} width={5} height={5} rx={0.5} stroke="#6C707E" />
  </svg>
);

const StructureDark: FC<
  Omit<ComponentProps<'svg'>, 'size'> & { size: number }
> = ({
  size,
  className,
  role,
  'aria-label': ariaLabel,
  'aria-hidden': ariaHidden,
}) => (
  <svg
    width={size}
    height={size}
    viewBox="0 0 16 16"
    fill="none"
    xmlns="http://www.w3.org/2000/svg"
    className={className}
    role={role}
    aria-label={ariaLabel}
    aria-hidden={ariaHidden}
  >
    <rect x={8.5} y={8.5} width={5} height={5} rx={0.5} stroke="#CED0D6" />
    <rect x={1.5} y={8.5} width={5} height={5} rx={0.5} stroke="#CED0D6" />
    <rect x={1.5} y={1.5} width={5} height={5} rx={0.5} stroke="#CED0D6" />
  </svg>
);

export const Structure: FC<StructureProps> = ({
  size = 16,
  mode = 'light',
  className,
  'aria-label': ariaLabel,
  ...props
}) => {
  const SvgComponent = mode === 'light' ? StructureLight : StructureDark;

  return (
    <SvgComponent
      size={size}
      className={cn('inline-block shrink-0', className)}
      role={ariaLabel ? 'img' : 'presentation'}
      aria-label={ariaLabel}
      aria-hidden={!ariaLabel}
      {...props}
    />
  );
};

export default Structure;
